import { chromium } from '@playwright/test'
import fs from 'node:fs/promises'
await fs.mkdir('.cache/stremio-browser',{recursive:true})
const browser=await chromium.launch({channel:'msedge',headless:true})
const mobile=process.env.NOCTA_TEST_MOBILE==='true'
const page=await browser.newPage(mobile?{viewport:{width:390,height:844},isMobile:true,hasTouch:true}:{})
const errors=[];page.on('pageerror',e=>errors.push(e.message))
try {
 await page.goto('http://127.0.0.1:5176/configuracoes')
 await page.getByRole('checkbox').check()
 await page.getByRole('button',{name:'Consultar fontes'}).click()
 await page.getByRole('button',{name:'Reproduzir mp4',exact:true}).click()
 let video=page.locator('video')
 await video.evaluate(el=>el.play())
 await page.waitForFunction(()=>document.querySelector('video')?.currentTime>1)
 const mp4=await video.evaluate(el=>({time:el.currentTime,width:el.videoWidth,duration:el.duration}))
 await video.evaluate(el=>{el.pause();el.currentTime=4})
 await page.waitForFunction(()=>document.querySelector('video')?.currentTime>=4)
 await page.getByRole('button',{name:'Reproduzir hls',exact:true}).click()
 video=page.locator('video')
 await page.waitForFunction(()=>document.querySelector('video')?.readyState>=2)
 await video.evaluate(el=>el.play())
 await page.waitForFunction(()=>document.querySelector('video')?.currentTime>1)
 const hls=await video.evaluate(el=>({time:el.currentTime,width:el.videoWidth,duration:el.duration}))
 const tracks=await page.getByLabel('Faixa de áudio').locator('option').allTextContents()
 await page.getByLabel('Faixa de áudio').selectOption('1')
 await page.waitForTimeout(800)
 if(await page.getByLabel('Faixa de áudio').inputValue()!=='1') throw new Error('Audio selection failed')
 await page.waitForFunction(time=>document.querySelector('video')?.currentTime>time+0.2,hls.time)
 await page.screenshot({path:`.cache/stremio-browser/${mobile?'mobile':'desktop'}.png`,fullPage:true})
 await page.getByLabel('Tipo experimental').selectOption('series')
 await page.getByLabel('Identificador experimental').fill('tmdb:1')
 await page.getByLabel('Episódio experimental').fill('2')
 await page.getByRole('button',{name:'Consultar fontes'}).click()
 await page.getByRole('button',{name:'Reproduzir mp4',exact:true}).click()
 await page.locator('video').evaluate(el=>el.play())
 await page.waitForFunction(()=>document.querySelector('video')?.currentTime>1)
 const series=await page.locator('video').evaluate(el=>({time:el.currentTime,width:el.videoWidth}))
 const result={mp4,hls,tracks,series,errors,android:'not tested'}
 await fs.writeFile(`.cache/stremio-browser/${mobile?'mobile-result':'result'}.json`,JSON.stringify(result,null,2));console.log(JSON.stringify(result))
} catch(error) { console.log((await page.locator('body').innerText()).slice(-3000)); await page.screenshot({path:'.cache/stremio-browser/failure.png',fullPage:true}); throw error } finally {await browser.close()}
